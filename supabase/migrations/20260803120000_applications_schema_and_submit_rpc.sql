-- Slice 3 PR 3.1 — applications schema, candidate-own RLS, Auth-bound submit RPC
-- (Accepted D-035–D-045; docs/24-slice-3-schema-and-journey-proposal.md).
-- No UI, Server Actions, matcher SQL, employer policies, or fixture inserts.

-- ---------------------------------------------------------------------------
-- applications
-- ---------------------------------------------------------------------------

create table public.applications (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null
    references public.candidate_profiles (id)
    on delete cascade,
  vacancy_id uuid not null
    references public.vacancies (id)
    on delete restrict,
  status text not null,
  submitted_at timestamptz not null default now(),
  snapshot_version integer not null,
  candidate_snapshot jsonb not null,
  vacancy_snapshot jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint applications_status_chk
    check (status = 'submitted'),
  constraint applications_snapshot_version_chk
    check (snapshot_version = 1),
  constraint applications_candidate_snapshot_object_chk
    check (jsonb_typeof(candidate_snapshot) = 'object'),
  constraint applications_vacancy_snapshot_object_chk
    check (jsonb_typeof(vacancy_snapshot) = 'object'),
  constraint applications_candidate_vacancy_key
    unique (candidate_id, vacancy_id)
);

comment on table public.applications is
  'Slice 3 candidate submissions: live FKs + immutable RPC-built snapshots; status submitted only.';

comment on column public.applications.candidate_id is
  'Set only from auth.uid() inside submit_candidate_application; ON DELETE CASCADE with profile (Accepted D-038). RESTRICT would block auth.users → candidate_profiles cascade deletion for applicants.';

comment on column public.applications.vacancy_id is
  'ON DELETE RESTRICT preserves submission history; vacancies are soft-withdrawn in Slice 2.';

comment on column public.applications.snapshot_version is
  'Slice 3 locked to 1; later versions require a new Accepted decision.';

comment on column public.applications.candidate_snapshot is
  'Immutable v1 snapshot generated by submit_candidate_application from trusted rows.';

comment on column public.applications.vacancy_snapshot is
  'Immutable v1 snapshot generated by submit_candidate_application from trusted rows.';

-- Unique (candidate_id, vacancy_id) already indexes candidate_id as leftmost column.
create index applications_vacancy_id_idx
  on public.applications (vacancy_id);

-- ---------------------------------------------------------------------------
-- RLS: candidate SELECT own rows only
-- ---------------------------------------------------------------------------

alter table public.applications enable row level security;

create policy applications_select_own
  on public.applications
  for select
  to authenticated
  using (
    candidate_id = (select auth.uid())
  );

-- ---------------------------------------------------------------------------
-- Privileges: no direct authenticated write
-- ---------------------------------------------------------------------------

revoke all on table public.applications from public, anon, authenticated;
grant select on table public.applications to authenticated;
grant all on table public.applications to service_role;

-- ---------------------------------------------------------------------------
-- submit_candidate_application — Auth-bound atomic insert / already_applied
-- ---------------------------------------------------------------------------

create or replace function public.submit_candidate_application(p_vacancy_id uuid)
returns jsonb
language plpgsql
security definer
set search_path to pg_catalog, public
as $$
declare
  uid uuid := auth.uid();
  profile public.candidate_profiles%rowtype;
  vacancy public.vacancies%rowtype;
  company_name text;
  snapshot_job_category text;
  ts timestamptz := clock_timestamp();
  new_id uuid;
  existing_id uuid;
  candidate_languages_json jsonb;
  vacancy_languages_json jsonb;
  employment_sorted text[];
  shifts_sorted text[];
  vacancy_employment_sorted text[];
  vacancy_shifts_sorted text[];
  candidate_snap jsonb;
  vacancy_snap jsonb;
begin
  if uid is null then
    return jsonb_build_object('result', 'unavailable');
  end if;

  if p_vacancy_id is null then
    return jsonb_build_object('result', 'unavailable');
  end if;

  -- 1–2. Auth identity → canonical candidate profile (locked).
  select * into profile
  from public.candidate_profiles
  where id = uid
  for update;

  if not found then
    return jsonb_build_object('result', 'incomplete');
  end if;

  -- 3–4. Completion gate before any application resolution or ID exposure.
  if profile.onboarding_completed_at is null then
    return jsonb_build_object('result', 'incomplete');
  end if;

  -- 5. Inventory / lifecycle / source / publication gate (D-033 helper; no matcher).
  if not exists (
    select 1
    from public.visible_seed_vacancy_ids() as visible (id)
    where visible.id = p_vacancy_id
  ) then
    return jsonb_build_object('result', 'unavailable');
  end if;

  select v.* into vacancy
  from public.vacancies v
  where v.id = p_vacancy_id;

  if not found then
    return jsonb_build_object('result', 'unavailable');
  end if;

  select c.name into company_name
  from public.companies c
  where c.id = vacancy.company_id;

  if company_name is null then
    return jsonb_build_object('result', 'unavailable');
  end if;

  -- 6. Idempotent retry for completed candidates, then race-safe insert.
  select a.id into existing_id
  from public.applications a
  where a.candidate_id = uid
    and a.vacancy_id = p_vacancy_id;

  if existing_id is not null then
    return jsonb_build_object(
      'result', 'already_applied',
      'application_id', existing_id
    );
  end if;

  -- Snapshot integrity: vacancy category must be in candidate preferences.
  -- Narrow membership check only — full product matcher stays in PR 3.3 TS.
  -- Missing membership uses unavailable; product-level match denial is PR 3.3.
  select pref.category
  into snapshot_job_category
  from unnest(profile.job_categories) as pref (category)
  where pref.category = vacancy.job_category
  limit 1;

  if snapshot_job_category is null then
    return jsonb_build_object('result', 'unavailable');
  end if;

  select coalesce(
    (
      select array_agg(x order by x)
      from unnest(profile.employment_types) as x
    ),
    '{}'::text[]
  )
  into employment_sorted;

  select coalesce(
    (
      select array_agg(x order by x)
      from unnest(profile.shift_preferences) as x
    ),
    '{}'::text[]
  )
  into shifts_sorted;

  select coalesce(
    (
      select array_agg(x order by x)
      from unnest(vacancy.employment_types) as x
    ),
    '{}'::text[]
  )
  into vacancy_employment_sorted;

  select coalesce(
    (
      select array_agg(x order by x)
      from unnest(vacancy.shift_requirements) as x
    ),
    '{}'::text[]
  )
  into vacancy_shifts_sorted;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'language_code', cl.language_code,
        'proficiency', cl.proficiency
      )
      order by cl.language_code
    ),
    '[]'::jsonb
  )
  into candidate_languages_json
  from public.candidate_languages cl
  where cl.candidate_id = uid
    and exists (
      select 1
      from public.vacancy_language_requirements vlr
      where vlr.vacancy_id = p_vacancy_id
        and vlr.language_code = cl.language_code
    );

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'language_code', vlr.language_code,
        'min_proficiency', vlr.min_proficiency
      )
      order by vlr.language_code
    ),
    '[]'::jsonb
  )
  into vacancy_languages_json
  from public.vacancy_language_requirements vlr
  where vlr.vacancy_id = p_vacancy_id;

  candidate_snap := jsonb_build_object(
    'display_name', profile.display_name,
    'job_category', snapshot_job_category,
    'german_comfort', profile.german_comfort,
    'languages', candidate_languages_json,
    'work_authorisation_declared', profile.work_authorisation_declared,
    'available_from',
      case
        when profile.available_from is null then null
        else to_char(profile.available_from, 'YYYY-MM-DD')
      end,
    'employment_types', to_jsonb(employment_sorted),
    'shift_preferences', to_jsonb(shifts_sorted)
  );

  vacancy_snap := jsonb_build_object(
    'vacancy_id', vacancy.id,
    'title', vacancy.title,
    'employer_display_name', company_name,
    'source', vacancy.source,
    'demo_label', 'Demo vacancy',
    'city', vacancy.city,
    'job_category', vacancy.job_category,
    'employment_types', to_jsonb(vacancy_employment_sorted),
    'shift_requirements', to_jsonb(vacancy_shifts_sorted),
    'german_requirement', vacancy.german_requirement,
    'language_requirements', vacancy_languages_json,
    'available_from',
      case
        when vacancy.available_from is null then null
        else to_char(vacancy.available_from, 'YYYY-MM-DD')
      end
  );

  begin
    insert into public.applications (
      candidate_id,
      vacancy_id,
      status,
      submitted_at,
      snapshot_version,
      candidate_snapshot,
      vacancy_snapshot,
      created_at,
      updated_at
    )
    values (
      uid,
      p_vacancy_id,
      'submitted',
      ts,
      1,
      candidate_snap,
      vacancy_snap,
      ts,
      ts
    )
    returning id into new_id;

    return jsonb_build_object(
      'result', 'submitted',
      'application_id', new_id
    );
  exception
    when unique_violation then
      select a.id into existing_id
      from public.applications a
      where a.candidate_id = uid
        and a.vacancy_id = p_vacancy_id;

      if existing_id is null then
        raise;
      end if;

      return jsonb_build_object(
        'result', 'already_applied',
        'application_id', existing_id
      );
  end;
end;
$$;

comment on function public.submit_candidate_application(uuid) is
  'PR 3.1 Auth-bound submit: auth.uid() only; completion before application resolution; visible_seed vacancy gate; candidate job_categories membership for snapshot job_category; RPC-built snapshot v1; unique-safe submitted/already_applied. Category miss → unavailable; full product match denial remains PR 3.3. No matcher in SQL. Never accepts candidate UUID, snapshots, status, or timestamps.';

revoke all on function public.submit_candidate_application(uuid) from public, anon;
grant execute on function public.submit_candidate_application(uuid) to authenticated;
